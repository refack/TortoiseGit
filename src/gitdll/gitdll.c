int git_diff_flush(const GIT_DIFF diff)
{
	struct diff_queue_struct *q = &diff_queued_diff;
	struct rev_info* p_Rev = diff;

	if(q->nr == 0)
		return 0;

	for (int i = 0; i < q->nr; ++i)
		diff_free_filepair(q->queue[i]);

	if(q->queue)
	{
		free((void*)q->queue);
		q->queue = NULL;
		q->nr = q->alloc = 0;
	}

	if (p_Rev->diffopt.close_file)
		fclose(p_Rev->diffopt.file);

	free_diffstat_info(&p_Rev->diffstat);
	return 0;
}

int git_root_diff(const GIT_DIFF diff, const GIT_HASH hash, GIT_FILE* file, int* count, const int isstat)
{
	struct object_id oid = {};
	struct diff_queue_struct *q = &diff_queued_diff;

	struct rev_info* p_Rev = diff;

	hashcpy(oid.hash, hash, the_repository->hash_algo);
	oid.algo = tgit_repo_hash_algo();

	diff_root_tree_oid(&oid, "", &p_Rev->diffopt);

	if(isstat)
	{
		diffcore_std(&p_Rev->diffopt);

		memset(&p_Rev->diffstat, 0, sizeof(struct diffstat_t));
		for (int i = 0; i < q->nr; ++i) {
			struct diff_filepair *p = q->queue[i];
			//if (check_pair_status(p))
			diff_flush_stat(p, &p_Rev->diffopt, &p_Rev->diffstat);
		}
	}

	if (file)
		*file = q;
	if (count)
		*count = q->nr;

	return 0;
}

int git_do_diff(const GIT_DIFF diff, const GIT_HASH hash1, const GIT_HASH hash2, GIT_FILE* file, int* count, const int isstat)
{
	struct object_id oid1 = {};
	struct object_id oid2 = {};
	struct diff_queue_struct *q = &diff_queued_diff;

	struct rev_info* p_Rev = (struct rev_info*)diff;

	hashcpy(oid1.hash, hash1, the_repository->hash_algo);
	oid1.algo = tgit_repo_hash_algo();
	hashcpy(oid2.hash, hash2, the_repository->hash_algo);
	oid2.algo = tgit_repo_hash_algo();

	struct diff_options* diffopt = &p_Rev->diffopt;
	diff_tree_oid(&oid1, &oid2, "", diffopt);

	if(isstat)
	{
		diffcore_std(&p_Rev->diffopt);
		memset(&p_Rev->diffstat, 0, sizeof(struct diffstat_t));
		for (int i = 0; i < q->nr; ++i) {
			struct diff_filepair *p = q->queue[i];
			//if (check_pair_status(p))
			diff_flush_stat(p, &p_Rev->diffopt, &p_Rev->diffstat);
		}
	}
	odb_close_tgit(the_repository->objects);
	if(file)
		*file = q;
	if(count)
		*count = q->nr;
	return 0;
}

int git_get_diff_file(const GIT_DIFF diff, const GIT_FILE file, const int i, char** newname, char** oldname, int* IsDir, char* status, int* IsBin, int* inc, int* dec)
{
	struct rev_info* const p_Rev = (struct rev_info*)diff;

	const struct diff_queue_struct* q = (struct diff_queue_struct *)file;
	if(file == NULL)
		return -1;
	if(i>=q->nr)
		return -1;

	assert(newname && oldname && status && IsDir);

	*newname = q->queue[i]->two->path;
	*oldname = q->queue[i]->one->path;
	*status = q->queue[i]->status;
	if (*status == 'D')
		*IsDir = (q->queue[i]->one->mode & S_IFDIR) == S_IFDIR;
	else
		*IsDir = (q->queue[i]->two->mode & S_IFDIR) == S_IFDIR;

	if (q->queue[i]->one->mode && q->queue[i]->two->mode && DIFF_PAIR_TYPE_CHANGED(q->queue[i]))
		*IsDir = 0;

	if(p_Rev->diffstat.files)
	{
		int j;
		for (j = 0; j < p_Rev->diffstat.nr; ++j)
		{
			if(strcmp(*newname,p_Rev->diffstat.files[j]->name)==0)
				break;
		}
		if( j== p_Rev->diffstat.nr)
		{
			*IsBin=1;
			*inc=0;
			*dec=0;
			return 0;
		}
		if(IsBin)
			*IsBin = p_Rev->diffstat.files[j]->is_binary;
		if(inc)
			*inc = (int)p_Rev->diffstat.files[j]->added;
		if(dec)
			*dec = (int)p_Rev->diffstat.files[j]->deleted;
	}else
	{
		*IsBin=1;
		*inc=0;
		*dec=0;
	}

	return 0;
}

