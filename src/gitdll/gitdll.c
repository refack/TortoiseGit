int git_get_sha1(const char *name, GIT_HASH sha1)
{
	struct object_id oid = { 0 };
	const int ret = repo_get_oid(the_repository, name, &oid);
	hashcpy(sha1, oid.hash, the_repository->hash_algo);
	return ret;
}

/*
 * Hash algorithm of the currently opened repository, using git's own
 * GIT_HASH_* indices (0 = unknown, 1 = sha1, 2 = sha256). TortoiseGit latches
 * this once after git_init() and sizes its object ids accordingly, see GitHash.h.
 */
static int tgit_repo_hash_algo(void)
{
	if (!the_repository || !the_repository->hash_algo)
		return GIT_HASH_UNKNOWN;
	return (int)hash_algo_by_ptr(the_repository->hash_algo);
}

int git_get_hash_algo(void)
{
	return tgit_repo_hash_algo();
}

int git_init(const wchar_t* env)
{
	_set_fmode(_O_BINARY);
	_setmode(_fileno(stdin), _O_BINARY);
	_setmode(_fileno(stdout), _O_BINARY);
	_setmode(_fileno(stderr), _O_BINARY);

	cleanup_chdir_notify();
	fscache_flush();
	reset_setup();
	reset_git_env(env);
	assert(getenv("HOME")); // make sure HOME is already set
	drop_all_attr_stacks();
	repo_config_clear(the_repository);
	g_prefix = setup_git_directory(the_repository);
	repo_config(the_repository, git_default_config, NULL);
	ref_store_release_and_clear(the_repository);
	clear_ref_decorations();

	/*
	 * sha1 and sha256 are both handled now (callers size object ids off
	 * git_get_hash_algo(), see GitHash.h); anything else we do not know about.
	 */
	if (tgit_repo_hash_algo() == GIT_HASH_UNKNOWN)
		die("Unsupported repository object format.");

	return 0;
}

static int git_parse_commit_author(struct GIT_COMMIT_AUTHOR* author, const char* pbuff)
{
	const char* end = strchr(pbuff, '<');
	if (!end || end - pbuff - 1 >= INT_MAX)
		return -1;
	author->Name = pbuff;
	author->NameSize = (int)(end - pbuff - 1);

	pbuff = end +1;
	end = strchr(pbuff, '>');
	if (!end || end[1] != ' ' || end - pbuff >= INT_MAX)
		return -1;
	author->Email = pbuff ;
	author->EmailSize = (int)(end - pbuff);

	pbuff = end + 2;

	author->Date = parse_timestamp(pbuff, &end, 10);
	if (end == pbuff || !end || *end != ' ' || end[1] != '+' && end[1] != '-' || !isdigit(end[2]) || !isdigit(end[3]) || !isdigit(end[4]) || !isdigit(end[5]))
		return -1;
	pbuff = end + 1;
	author->TimeZone = strtol(pbuff, NULL, 10);

	return 0;
}

int git_parse_commit(GIT_COMMIT *commit)
{
	const struct commit* p = commit->m_pGitCommit;

	hashcpy(commit->m_hash, p->object.oid.hash, the_repository->hash_algo);

	commit->m_Encode = NULL;
	commit->m_EncodeSize = 0;

	commit->buffer = detach_commit_buffer(commit->m_pGitCommit, NULL);

	const char* pbuf = commit->buffer;
	while(pbuf)
	{
		if (strncmp(pbuf, "author ", strlen("author ")) == 0)
		{
			const int ret = git_parse_commit_author(&commit->m_Author, pbuf + strlen("author "));
			if(ret)
				return -4;
		}
		else if (strncmp(pbuf, "committer ", strlen("committer ")) == 0)
		{
			const int ret = git_parse_commit_author(&commit->m_Committer, pbuf + strlen("committer "));
			if(ret)
				return -5;

			pbuf = strchr(pbuf,'\n');
			if(pbuf == NULL)
				return -6;
		}
		else if (strncmp(pbuf, "encoding ", strlen("encoding ")) == 0)
		{
			pbuf += strlen("encoding ");
			commit->m_Encode=pbuf;
			const char* end = strchr(pbuf,'\n');
			if (!pbuf || end - pbuf >= INT_MAX)
				return -7;
			commit->m_EncodeSize= (int)(end -pbuf);
		}

		// the headers end after the first empty line
		else if (*pbuf == '\n')
		{
			++pbuf;

			commit->m_Subject=pbuf;
			const char* end = strchr(pbuf,'\n');
			if (!end)
			{
				const size_t subjLen = strlen(pbuf);
				if (subjLen >= INT_MAX)
					return -8;
				commit->m_SubjectSize = (int)subjLen;
			}
			else
			{
				if (end - pbuf >= INT_MAX)
					return -9;
				commit->m_SubjectSize = (int)(end - pbuf);
				pbuf = end +1;
				commit->m_Body = pbuf;
				const size_t bodyLen = strlen(pbuf);
				if (bodyLen >= INT_MAX)
					return -10;
				commit->m_BodySize = (int)bodyLen;
				return 0;
			}
		}

		pbuf = strchr(pbuf,'\n');
		if(pbuf)
			++pbuf;
	}
	return 0;
}

int git_get_commit_from_hash(GIT_COMMIT* commit, const GIT_HASH hash)
{
	struct commit *p;
	struct object_id oid = {0};

	if (commit == NULL)
		return -1;

	memset(commit,0,sizeof(GIT_COMMIT));

	hashcpy(oid.hash, hash, the_repository->hash_algo);
	oid.algo = tgit_repo_hash_algo();

	commit->m_pGitCommit = p = lookup_commit(the_repository, &oid);

	if(p == NULL)
		return -1;

	const int ret = repo_parse_commit(the_repository, p);
	if( ret )
		return ret;

	return git_parse_commit(commit);
}

int git_get_commit_first_parent(const GIT_COMMIT* commit, GIT_COMMIT_LIST* list)
{
	const struct commit *p = commit->m_pGitCommit;

	if(list == NULL)
		return -1;

	*list = p->parents;
	return 0;
}

int git_commit_is_root(const GIT_COMMIT* commit)
{
	const struct commit* p = commit->m_pGitCommit;
	return (struct commit_list**)p->parents ? 1 : 0;
}

int git_get_commit_next_parent(GIT_COMMIT_LIST *list, GIT_HASH hash)
{
	if (list == NULL)
		return -1;

	struct commit_list* l = *(struct commit_list**)list;
	if (l == NULL)
		return -1;

	if(hash)
		hashcpy(hash, l->item->object.oid.hash, the_repository->hash_algo);

	*list = l->next;
	return 0;

}


int git_free_commit(GIT_COMMIT *commit)
{
	struct commit *p = commit->m_pGitCommit;

	if( p->parents)
		commit_list_free(p->parents);

	if (p->maybe_tree)
		free_tree_buffer(p->maybe_tree);

	free_commit_buffer(the_repository->parsed_objects, p);
	free((void*)commit->buffer);

	p->object.parsed = 0;
	p->parents = 0;
	p->maybe_tree = NULL;

	memset(commit,0,sizeof(GIT_COMMIT));
	return 0;
}

int git_open_log(GIT_LOG* handle, const int argc, const char** argv)
{
	struct setup_revision_opt opt;

	assert(argc && argv);

	/* clear flags */
	const unsigned int obj_size = get_max_object_index(the_repository);
	for (unsigned int i = 0; i < obj_size; ++i)
	{
		struct object* ob = get_indexed_object(the_repository, i);
		if(ob)
		{
			ob->flags=0;
			if (ob->parsed && ob->type == OBJ_COMMIT)
			{
				struct commit* commit = (struct commit*)ob;
				commit_list_free(commit->parents);
				commit->parents = NULL;
				if (commit->maybe_tree)
					free_tree_buffer(commit->maybe_tree);
				commit->maybe_tree = NULL;
				ob->parsed = 0;
			}
		}
	}

	struct rev_info* p_Rev = malloc(sizeof(struct rev_info));
	if (!p_Rev)
		return -1;

	memset(p_Rev,0,sizeof(struct rev_info));
	*handle = p_Rev; // set this before an exception may be thrown in gitdll so that we don't leak memory

	ref_store_release_and_clear(the_repository);
	clear_ref_decorations();

	repo_init_revisions(the_repository, p_Rev, g_prefix);
	p_Rev->diff = 1;

	memset(&opt, 0, sizeof(opt));
	opt.def = "HEAD";

	cmd_log_init_tgit(argc, argv, g_prefix, p_Rev, &opt);

	p_Rev->pPrivate = (void*)argv; // set last, so if an exception is thrown in gitdll it will not get freed twice
	return 0;

}
