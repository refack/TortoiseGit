int git_get_log_estimate_commit_count(const GIT_LOG handle)
{
	struct rev_info* p_Rev = (struct rev_info*)handle;

	const struct commit_list* list = p_Rev->commits;
	int n = 0;
	while (list)
	{
		const struct commit* commit = list->item;
		const unsigned int flags = commit->object.flags;
		list = list->next;
		if (!(flags & (TREESAME | UNINTERESTING)))
			++n;
	}
	return n;
}

int git_get_log_nextcommit(const GIT_LOG handle, GIT_COMMIT* commit, const int follow)
{
	struct rev_info* p_Rev = (struct rev_info*)handle;
	if(!commit)
		return -1;

	memset(commit, 0, sizeof(GIT_COMMIT));

	commit->m_pGitCommit = get_revision(p_Rev);
	if( commit->m_pGitCommit == NULL)
		return -2;

	if (follow)
	{
		p_Rev->diffopt.no_free = 1;
		if (!log_tree_commit(p_Rev, (struct commit* )commit->m_pGitCommit))
		{
			commit->m_ignore = 1;
			return 0;
		}
	}
	commit->m_ignore = 0;

	const int ret = git_parse_commit(commit);
	if(ret)
		return ret;

	return 0;
}

