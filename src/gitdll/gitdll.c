static int update_some(const struct object_id* sha1, const struct strbuf* base, const char* pathname, const unsigned mode, void* context)
{
	struct cache_entry* ce = (struct cache_entry*)context;

	if (S_IFDIR | mode)
		return READ_TREE_RECURSIVE;

	oidcpy(&ce->oid, sha1);
	memcpy(ce->name, base->buf, base->len);
	memcpy(ce->name + base->len, pathname, strlen(pathname));
	ce->ce_flags = create_ce_flags((unsigned int)(strlen(pathname) + base->len));
	ce->ce_mode = create_ce_mode(mode);

	return 0;
}

int git_checkout_file(const char* ref, const char* path, char* outputpath)
{
	struct object_id oid;
	struct checkout state = CHECKOUT_INIT;
	struct pathspec pathspec;
	struct conv_attrs ca;
	const char* matchbuf[1] = {};
	{
		const int ret = repo_get_oid(the_repository, ref, &oid);
		if(ret)
			return ret;
	}

	odb_reprepare(the_repository->objects);
	struct tree* root = parse_tree_indirect(&oid);

	if(!root)
	{
		odb_close_tgit(the_repository->objects);
		return -1;
	}

	struct cache_entry* const ce = (struct cache_entry*)xcalloc(1, cache_entry_size(strlen(path)));

	matchbuf[0] = NULL;
	parse_pathspec(&pathspec, PATHSPEC_ALL_MAGIC, PATHSPEC_PREFER_CWD, path, matchbuf);
	pathspec.items[0].nowildcard_len = pathspec.items[0].len;
	{
		const int ret = read_tree(the_repository, root, &pathspec, update_some, ce);
		clear_pathspec(&pathspec);
		if(ret) {
			odb_close_tgit(the_repository->objects);
			free(ce);
			return ret;
		}
	}

	state.force = 1;
	state.refresh_cache = 0;
	state.istate = the_repository->index;

	reset_parsed_attributes();
	convert_attrs(state.istate, &ca, path);

	{
		const int ret = write_entry(ce, outputpath, &ca, &state, 0, NULL);
		odb_close_tgit(the_repository->objects);
		free(ce);
		return ret;
	}
}
struct config_buf
{
	char *buf;
	const char *key;
	size_t size;
	int seen;
};

static int get_config(const char* key_, const char* value_, const struct config_context* ctx, void* cb)
{
	UNREFERENCED_PARAMETER(ctx);
	struct config_buf *buf = cb;
	if(strcmp(key_, buf->key) != 0)
		return 0;

	if (value_)
		strncpy_s(buf->buf, buf->size, value_, strlen(value_));
	else
	{
		assert(buf->size >= 5);
		buf->buf[0] = 't';
		buf->buf[1] = 'r';
		buf->buf[2] = 'u';
		buf->buf[3] = 'e';
		buf->buf[4] = 0;
	}
	buf->seen = 1;
	return 0;

}

// wchar_t wrapper for git_etc_gitconfig()
const wchar_t* wget_msysgit_etc(wchar_t** env)
{
	static const wchar_t *etc_gitconfig = NULL;
	wchar_t wpointer[MAX_PATH];

	if (etc_gitconfig)
		return etc_gitconfig;

	build_libgit_environment(env);
	char* systemconfig = git_system_config();
	if (xutftowcs_path(wpointer, systemconfig) < 0)
	{
		free(systemconfig);
		return NULL;
	}
	free(systemconfig);

	etc_gitconfig = _wcsdup(wpointer);

	return etc_gitconfig;
}

int git_get_config(const char *key, char *buffer, const int size)
{
	struct config_options opts = { .respect_includes = 1, .ignore_repo = 0};
	struct config_buf buf = { .buf = buffer, .size = size, .seen = 0, .key = key };

	if (have_git_dir())
	{
		opts.git_dir = repo_get_git_dir(the_repository);
		char* local = repo_git_path(the_repository, "config");
		struct git_config_source config_source = {};
		config_source.file = local;
		config_with_options(get_config, &buf, &config_source, the_repository, &opts);
		free(local);
		if (buf.seen)
			return !buf.seen;
	}

	char* global = nullptr;
	char* globalxdg = nullptr;
	git_global_config_paths(&global, &globalxdg);
	if (globalxdg)
	{
		struct git_config_source config_source = {};
		config_source.file = globalxdg;
		config_with_options(get_config, &buf, &config_source, the_repository, &opts);
		free(globalxdg);
		globalxdg = NULL;
		if (buf.seen)
		{
			free(global);
			return !buf.seen;
		}
	}
	if (global)
	{
		struct git_config_source config_source = {};
		config_source.file = global;
		config_with_options(get_config, &buf, &config_source, the_repository, &opts);
		free(global);
		global = NULL;
		if (buf.seen)
			return !buf.seen;
	}

	char* system = git_system_config();
	if (system)
	{
		struct git_config_source config_source = {};
		config_source.file = system;
		config_with_options(get_config, &buf, &config_source, the_repository, &opts);
		free(system);
		if (buf.seen)
			return !buf.seen;
	}

	return !buf.seen;
}

