int git_set_config(const char* key, const char* value, const CONFIG_TYPE type)
{
	char* config_exclusive_filename;

	switch(type)
	{
	case CONFIG_LOCAL:
		if (!the_repository || !the_repository->gitdir)
			die("repository not correctly initialized.");
		config_exclusive_filename = repo_git_path(the_repository, "config");
		break;
	case CONFIG_GLOBAL:
	case CONFIG_XDGGLOBAL:
		{
			char* global = NULL;
			char* globalxdg = NULL;
			git_global_config_paths(&global, &globalxdg);
			if (type == CONFIG_GLOBAL)
			{
				config_exclusive_filename = global;
				global = NULL;
			}
			else
			{
				config_exclusive_filename = globalxdg;
				globalxdg = NULL;
			}
			free(global);
			free(globalxdg);
		}
		break;
	default:
		die("repository not correctly initialized.");
	}

	if(!config_exclusive_filename)
		return -1;

	const int ret = repo_config_set_multivar_in_file_gently(the_repository, config_exclusive_filename, key, value, NULL, NULL, 0);
	free(config_exclusive_filename);
	return ret;
}

struct mailmap_info {
	char *name;
	char *email;
};

struct mailmap_entry {
	/* name and email for the simple mail-only case */
	char *name;
	char *email;

	/* name and email for the complex mail and name matching case */
	struct string_list namemap;
};

int git_read_mailmap(GIT_MAILMAP *mailmap)
{
	struct string_list *map;
	int result;

	if (!mailmap)
		return -1;

	*mailmap = NULL;
	if ((map = (struct string_list *)calloc(1, sizeof(struct string_list))) == NULL)
		return -1;

	if ((result = read_mailmap(the_repository, map)) != 0)
	{
		clear_mailmap(map);
		free(map);
		return result;
	}

	if (!map->items)
	{
		clear_mailmap(map);
		free(map);
		 
		return -1;
	}

	*mailmap = map;
	return 0;
}

int git_lookup_mailmap(const GIT_MAILMAP mailmap, const char** email1, const char** name1, const char* email2, void* payload, const char *(*author2_cb)(void*))
{
	if (!mailmap)
		return -1;

	const struct string_list* map = (struct string_list*)mailmap;
	const struct string_list_item* si = string_list_lookup(map, email2);
	if (!si)
		return -1;

	struct mailmap_entry* me = (struct mailmap_entry*)si->util;
	if (me->namemap.nr) {
		/* The item has multiple items */
		const char* author2 = author2_cb(payload);
		struct string_list_item* subitem = string_list_lookup(&me->namemap, author2);
		if (subitem)
			me = (struct mailmap_entry*)subitem->util;
	}

	if (email1)
		*email1 = me->email;
	if (name1)
		*name1 = me->name;
	return 0;
}

void git_free_mailmap(const GIT_MAILMAP mailmap)
{
	if (!mailmap)
		return;

	clear_mailmap((struct string_list *)mailmap);
	free(mailmap);
}

